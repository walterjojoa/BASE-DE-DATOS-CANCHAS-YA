-- =============================================================
-- V04 - schedules
-- Opening hours of a field, one row per day of the week.
-- Hours are whole hours: opening_hour 8 and closing_hour 22 means 08:00-22:00.
-- Maps to the JPA entity com.canchaya.domain.Schedule.
-- =============================================================

CREATE TABLE schedules (
    id            BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    field_id      BIGINT      NOT NULL,
    day_of_week   VARCHAR(10) NOT NULL,
    opening_hour  INTEGER     NOT NULL,
    closing_hour  INTEGER     NOT NULL,

    CONSTRAINT fk_schedules_field  FOREIGN KEY (field_id) REFERENCES fields (id) ON DELETE CASCADE,
    CONSTRAINT uq_schedules_day    UNIQUE (field_id, day_of_week),
    CONSTRAINT ck_schedules_day    CHECK (day_of_week IN ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY',
                                                          'FRIDAY', 'SATURDAY', 'SUNDAY')),
    CONSTRAINT ck_schedules_hours  CHECK (opening_hour >= 0 AND closing_hour <= 24
                                          AND closing_hour > opening_hour)
);

COMMENT ON TABLE  schedules             IS 'Weekly opening hours of each field';
COMMENT ON COLUMN schedules.day_of_week IS 'English day name as java.time.DayOfWeek (MONDAY..SUNDAY)';
