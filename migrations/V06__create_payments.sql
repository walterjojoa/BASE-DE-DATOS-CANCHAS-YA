-- =============================================================
-- V06 - payments
-- Every attempt to pay a reservation's deposit (approved or declined).
-- Maps to the JPA entity com.canchaya.domain.Payment.
-- =============================================================

CREATE TABLE payments (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id   BIGINT        NOT NULL,
    amount           NUMERIC(12,2) NOT NULL,
    method           VARCHAR(20)   NOT NULL,
    status           VARCHAR(20)   NOT NULL,
    transaction_ref  VARCHAR(120),
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT fk_payments_reservation FOREIGN KEY (reservation_id) REFERENCES reservations (id) ON DELETE CASCADE,
    CONSTRAINT ck_payments_amount      CHECK (amount > 0),
    CONSTRAINT ck_payments_method      CHECK (method IN ('WOMPI', 'NEQUI', 'DAVIPLATA')),
    CONSTRAINT ck_payments_status      CHECK (status IN ('APPROVED', 'DECLINED'))
);

COMMENT ON TABLE  payments                 IS 'Deposit payment attempts of each reservation';
COMMENT ON COLUMN payments.method          IS 'WOMPI (card) | NEQUI | DAVIPLATA';
COMMENT ON COLUMN payments.transaction_ref IS 'Reference returned by the payment provider';
