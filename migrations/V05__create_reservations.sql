-- =============================================================
-- V05 - reservations
-- A player books a field on a date for a range of whole hours
-- [start_hour, end_hour). The deposit ("anticipo") is stored at
-- booking time so later price changes don't affect it.
-- Maps to the JPA entity com.canchaya.domain.Reservation.
-- =============================================================

CREATE TABLE reservations (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    field_id        BIGINT        NOT NULL,
    player_id       BIGINT        NOT NULL,
    date            DATE          NOT NULL,
    start_hour      INTEGER       NOT NULL,
    end_hour        INTEGER       NOT NULL,
    total_amount    NUMERIC(12,2) NOT NULL,
    deposit_amount  NUMERIC(12,2) NOT NULL,
    status          VARCHAR(20)   NOT NULL DEFAULT 'PENDING_PAYMENT',
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT fk_reservations_field   FOREIGN KEY (field_id)  REFERENCES fields (id) ON DELETE RESTRICT,
    CONSTRAINT fk_reservations_player  FOREIGN KEY (player_id) REFERENCES users (id)  ON DELETE RESTRICT,
    CONSTRAINT ck_reservations_hours   CHECK (start_hour >= 0 AND end_hour <= 24 AND end_hour > start_hour),
    CONSTRAINT ck_reservations_amounts CHECK (total_amount > 0 AND deposit_amount >= 0
                                              AND deposit_amount <= total_amount),
    CONSTRAINT ck_reservations_status  CHECK (status IN ('PENDING_PAYMENT', 'CONFIRMED', 'CANCELLED'))
);

COMMENT ON TABLE  reservations                IS 'Bookings of a field for whole hours on a date';
COMMENT ON COLUMN reservations.start_hour     IS 'First booked hour (inclusive)';
COMMENT ON COLUMN reservations.end_hour       IS 'Hour when the booking ends (exclusive)';
COMMENT ON COLUMN reservations.deposit_amount IS 'Deposit to pay online; the rest is paid at the field';
COMMENT ON COLUMN reservations.status         IS 'PENDING_PAYMENT -> CONFIRMED, or CANCELLED';
