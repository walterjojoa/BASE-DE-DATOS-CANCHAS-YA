-- =============================================================
-- V03 - fields
-- Synthetic football fields published by an OWNER.
-- Maps to the JPA entity com.canchaya.domain.Field.
-- =============================================================

CREATE TABLE fields (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(120)  NOT NULL,
    address         VARCHAR(200)  NOT NULL,
    latitude        DOUBLE PRECISION,
    longitude       DOUBLE PRECISION,
    price_per_hour  NUMERIC(12,2) NOT NULL,
    owner_id        BIGINT        NOT NULL,
    active          BOOLEAN       NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_fields_owner     FOREIGN KEY (owner_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_fields_price     CHECK (price_per_hour > 0),
    CONSTRAINT ck_fields_latitude  CHECK (latitude  IS NULL OR latitude  BETWEEN -90  AND 90),
    CONSTRAINT ck_fields_longitude CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_fields_name      CHECK (length(trim(name)) > 0)
);

COMMENT ON TABLE  fields                IS 'Synthetic football fields that can be booked';
COMMENT ON COLUMN fields.price_per_hour IS 'Price of one hour in Colombian pesos (COP)';
COMMENT ON COLUMN fields.latitude       IS 'WGS84 latitude, used by the map (Leaflet)';
COMMENT ON COLUMN fields.active         IS 'FALSE hides the field and blocks new reservations';
