-- =============================================================
-- V02 - users
-- Players (PLAYER), field owners (OWNER) and administrators (ADMIN).
-- Maps to the JPA entity com.canchaya.domain.User.
-- =============================================================

CREATE TABLE users (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(120) NOT NULL,
    email          VARCHAR(160) NOT NULL,
    password_hash  VARCHAR(255) NOT NULL,
    role           VARCHAR(20)  NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_users_email      UNIQUE (email),
    CONSTRAINT ck_users_role       CHECK (role IN ('PLAYER', 'OWNER', 'ADMIN')),
    CONSTRAINT ck_users_email_fmt  CHECK (email = lower(email) AND email LIKE '%_@_%._%'),
    CONSTRAINT ck_users_name       CHECK (length(trim(name)) > 0)
);

COMMENT ON TABLE  users               IS 'Platform users: players, field owners and administrators';
COMMENT ON COLUMN users.email         IS 'Login e-mail, always stored in lower case';
COMMENT ON COLUMN users.password_hash IS 'BCrypt hash, never the plain password';
COMMENT ON COLUMN users.role          IS 'PLAYER | OWNER | ADMIN';
