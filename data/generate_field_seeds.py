"""Generate seeds/S02__pasto_fields.sql and seeds/S03__pasto_schedules.sql
from data/pasto_fields.csv (the single source of the real fields of Pasto).

    python data/generate_field_seeds.py
"""
import csv
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
PRICE = 80000  # estimated COP per hour: no field publishes its price online
REFERENCE_OWNER = "referencias@canchaya.co"
DAYS = ["MONDAY", "TUESDAY", "WEDNESDAY", "THURSDAY", "FRIDAY", "SATURDAY", "SUNDAY"]


def q(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


rows = list(csv.DictReader(open(ROOT / "data" / "pasto_fields.csv", encoding="utf-8")))

values = ",\n".join(
    f"    ({i:>2}, {q(r['name'])}, {q(r['address'])}, {r['latitude']}, {r['longitude']}, {q(r['zone'])})"
    for i, r in enumerate(rows, start=1)
)
(ROOT / "seeds" / "S02__pasto_fields.sql").write_text(f"""-- =============================================================
-- S02 - Real synthetic football fields of Pasto ({len(rows)} fields)
-- GENERATED by data/generate_field_seeds.py from data/pasto_fields.csv
-- (do not edit by hand).
--
-- Source: public Google Maps listings, November 2026. These are real
-- businesses that have NOT joined CanchaYa, so they are loaded as
-- reference listings owned by the {REFERENCE_OWNER} account:
--   * price_per_hour = {PRICE} COP is an ESTIMATE (no field publishes it)
--   * phone numbers and Google ratings are intentionally not stored
-- ORDER BY keeps ids predictable: 1 = first row of the CSV.
-- =============================================================

INSERT INTO fields (name, address, latitude, longitude, price_per_hour, owner_id, zone, reference_listing)
SELECT v.name, v.address, v.lat, v.lng, {PRICE}, u.id, v.zone, TRUE
FROM (VALUES
{values}
) AS v(ord, name, address, lat, lng, zone)
JOIN users u ON u.email = {q(REFERENCE_OWNER)}
ORDER BY v.ord;
""", encoding="utf-8")

hours = {}
for r in rows:
    hours.setdefault((int(r["opening_hour"]), int(r["closing_hour"]), r["hours_source"]), []).append(r["name"])

blocks = []
for (opening, closing, source), names in hours.items():
    label = "published by the field" if source == "published" else "ESTIMATED"
    name_list = ",\n      ".join(q(n) for n in names)
    blocks.append(f"""-- {opening:02d}:00-{closing:02d}:00 every day ({label})
INSERT INTO schedules (field_id, day_of_week, opening_hour, closing_hour)
SELECT f.id, d.day, {opening}, {closing}
FROM fields f
CROSS JOIN unnest(ARRAY[{", ".join(q(d) for d in DAYS)}]) AS d(day)
WHERE f.name IN (
      {name_list});""")

(ROOT / "seeds" / "S03__pasto_schedules.sql").write_text(
    "-- =============================================================\n"
    "-- S03 - Opening hours of the Pasto fields\n"
    "-- GENERATED by data/generate_field_seeds.py (do not edit by hand).\n"
    "-- Only fields with hours_source=published come from the field itself;\n"
    "-- the rest are an estimate (08:00-22:00) until owners confirm them.\n"
    "-- =============================================================\n\n"
    + "\n\n".join(blocks) + "\n",
    encoding="utf-8",
)
print(f"{len(rows)} fields -> seeds/S02__pasto_fields.sql, seeds/S03__pasto_schedules.sql")
